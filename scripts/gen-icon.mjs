/**
 * Embed assets/workbench.svg as a UTF-8 data-URL module consumed by the
 * browser half (src/client/icon.ts). Kept as a script so the icon updates
 * without touching source code; SVG stays vector-sharp at any render size
 * (no compression blur like the old wide logo PNG).
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)))
const source = join(ROOT, 'assets', 'workbench.svg')
const target = join(ROOT, 'src', 'client', 'icon.ts')

const svg = readFileSync(source, 'utf8').trim()
const dataUrl = `data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg)}`
const content = [
  '/** Generated by scripts/gen-icon.mjs — do not edit by hand. */',
  `export const WORKBENCH_ICON = ${JSON.stringify(dataUrl)}`,
  '',
].join('\n')
writeFileSync(target, content)
console.log(`gen-icon: wrote ${target} (${dataUrl.length} bytes)`)
